import React, { useState } from 'react';
import { 
  Terminal, ChevronDown, ChevronUp, Copy, Check, Eye, 
  Search, Download, Shield, Layers, LayoutGrid, List
} from 'lucide-react';

// Helper to categorize gadgets into standard ROP groups
function categorizeGadgetList(gadgets) {
  const groups = {
    "syscall": [],
    "pop": [],
    "call": [],
    "jmp": [],
    "load mem": [],
    "write mem": [],
    "stack pivoting": [],
    "sp lifting": [],
    "load reg": [],
    "arithmetic/logic": [],
    "others": []
  };

  gadgets.forEach(g => {
    const rawInstr = (g.instructions || g.gadget || g.instr || '').trim();
    const addr = g.address || g.addr || '0x0';
    const item = { addr, instr: rawInstr, original: g };
    const lower = rawInstr.toLowerCase();

    if (lower.includes('syscall') || lower.includes('sysenter') || lower.includes('int 0x80') || lower.includes('svc') || lower.includes('ecall')) {
      groups["syscall"].push(item);
    } else if (lower.startsWith('call ') || lower.includes('; call ') || lower.endsWith('call')) {
      groups["call"].push(item);
    } else if (lower.startsWith('jmp ') || lower.includes('; jmp ') || lower.endsWith('jmp')) {
      groups["jmp"].push(item);
    } else if (lower.includes('rsp,') || lower.includes('esp,') || lower.includes('leave') || lower.includes('xchg eax, esp') || lower.includes('xchg esp')) {
      groups["stack pivoting"].push(item);
    } else if (lower.includes('add rsp,') || lower.includes('sub rsp,') || lower.includes('add esp,') || lower.includes('sub esp,')) {
      groups["sp lifting"].push(item);
    } else if (lower.startsWith('pop ') || lower.includes('; pop ')) {
      groups["pop"].push(item);
    } else if ((lower.includes('mov ') || lower.includes('ldr ')) && lower.includes('[') && lower.indexOf('[') > lower.indexOf(',')) {
      groups["load mem"].push(item);
    } else if ((lower.includes('mov ') || lower.includes('add ') || lower.includes('str ')) && lower.includes('[') && lower.indexOf('[') < lower.indexOf(',')) {
      groups["write mem"].push(item);
    } else if (lower.includes('xor ') || lower.includes('add ') || lower.includes('sub ') || lower.includes('and ') || lower.includes('or ')) {
      groups["arithmetic/logic"].push(item);
    } else {
      groups["others"].push(item);
    }
  });

  const result = {};
  for (const [k, v] of Object.entries(groups)) {
    if (v.length > 0) result[k] = v;
  }
  return result;
}

export default function BinaryGadgetGroup({ 
  group, 
  index, 
  defaultExpanded = true,
  onInspect,
  onSelectBinary
}) {
  const [isExpanded, setIsExpanded] = useState(defaultExpanded);
  const [viewMode, setViewMode] = useState('categories'); // 'categories' or 'list'
  const [filterQuery, setFilterQuery] = useState('');
  const [copiedKey, setCopiedKey] = useState(null);

  const { cleanName, rawName, arch, category, hash, reportId, rawReport, gadgets } = group;

  const handleCopy = (text, key) => {
    navigator.clipboard.writeText(text);
    setCopiedKey(key);
    setTimeout(() => setCopiedKey(null), 2000);
  };

  const handleInspectClick = (e) => {
    if (e) {
      e.preventDefault();
      e.stopPropagation();
    }
    const targetReport = rawReport || {
      id: reportId || cleanName,
      report_id: reportId || cleanName,
      architecture: arch,
      file_type: category,
      target_binary: { filename: rawName, hash: hash },
      gadgets: gadgets
    };
    if (onInspect) {
      onInspect(targetReport);
    } else {
      window.location.hash = `#/report/${encodeURIComponent(reportId || cleanName)}`;
    }
  };

  // Download this binary's gadgets as text file
  const handleDownloadText = (e) => {
    e.stopPropagation();
    let txt = `================================================================================\n`;
    txt += `                    ROPWEAVER DISCOVERED GADGETS CATALOG                        \n`;
    txt += `================================================================================\n`;
    txt += `Binary Name:         ${cleanName}\n`;
    txt += `Full Path:           ${rawName}\n`;
    txt += `Architecture:        ${arch}\n`;
    txt += `Format:              ${category}\n`;
    txt += `Binary Hash:         ${hash || 'N/A'}\n`;
    txt += `Report Identifier:   ${reportId || 'N/A'}\n`;
    txt += `Total Gadgets:       ${gadgets.length}\n`;
    txt += `================================================================================\n\n`;

    gadgets.forEach((g, i) => {
      const addr = g.address || g.addr || '0x0';
      const instr = g.instructions || g.gadget || '';
      txt += `[${(i + 1).toString().padStart(3, ' ')}]  ${addr.padEnd(18, ' ')} :  ${instr}\n`;
    });

    txt += `\n================================================================================\n`;
    txt += `Generated by ROPWeaver v1.2.3 — Cloud Registry\n`;

    const blob = new Blob([txt], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${cleanName}_gadgets.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  // Filter gadgets for this binary
  const filteredList = gadgets.filter(g => {
    if (!filterQuery) return true;
    const q = filterQuery.toLowerCase();
    const instr = (g.instructions || g.gadget || '').toLowerCase();
    const addr = (g.address || g.addr || '').toLowerCase();
    return instr.includes(q) || addr.includes(q);
  });

  const categorized = categorizeGadgetList(filteredList);

  return (
    <div className="binary-gadget-group-card">
      {/* Group Header */}
      <div 
        className="binary-gadget-group-header" 
        onClick={() => setIsExpanded(!isExpanded)}
        style={{ cursor: 'pointer' }}
      >
        <div className="group-header-left">
          {index && <span className="report-card-index mono">#{index}</span>}
          <Terminal size={18} className="text-accent-green" />
          <span 
            className="group-binary-title mono font-bold clickable-title"
            onClick={handleInspectClick}
            title="Inspect full report for this binary"
          >
            &gt;_ {cleanName}
          </span>
          <span className="badge badge-info mono">{arch.toUpperCase()}</span>
          <span className="badge badge-warning mono">{category.toUpperCase()}</span>
          <span className="badge badge-none mono text-accent-green" style={{ borderColor: 'rgba(0, 255, 136, 0.3)' }}>
            {gadgets.length} {gadgets.length === 1 ? 'Gadget' : 'Gadgets'}
          </span>
        </div>

        <div className="group-header-actions" onClick={(e) => e.stopPropagation()}>
          <button
            type="button"
            onClick={handleInspectClick}
            className="btn btn-outline-green btn-xs mono"
            title="Inspect full report with suggested groups and chains"
          >
            <Eye size={13} />
            <span>INSPECT REPORT</span>
          </button>

          <button
            type="button"
            onClick={handleDownloadText}
            className="btn btn-secondary btn-xs mono"
            title="Download gadgets as .txt file"
          >
            <Download size={13} />
            <span>.TXT</span>
          </button>

          <button
            type="button"
            onClick={() => setIsExpanded(!isExpanded)}
            className="btn btn-secondary btn-xs mono"
            title={isExpanded ? "Collapse group" : "Expand group"}
          >
            {isExpanded ? (
              <>
                <ChevronUp size={14} />
                <span>Hide</span>
              </>
            ) : (
              <>
                <ChevronDown size={14} />
                <span>Show ({gadgets.length})</span>
              </>
            )}
          </button>
        </div>
      </div>

      {/* Group Body when Expanded */}
      {isExpanded && (
        <div className="binary-gadget-group-body">
          {/* Sub Toolbar: In-file search & View Mode Toggle */}
          <div className="group-toolbar">
            <div className="group-search-wrap">
              <Search size={14} className="text-muted" />
              <input
                type="text"
                className="group-search-input mono text-xs"
                placeholder={`Search ${gadgets.length} gadgets in ${cleanName} (e.g. pop, syscall, rax, ret)...`}
                value={filterQuery}
                onChange={(e) => setFilterQuery(e.target.value)}
              />
              {filterQuery && (
                <button 
                  onClick={() => setFilterQuery('')} 
                  className="group-search-clear mono text-xs text-muted"
                >
                  ✕
                </button>
              )}
            </div>

            <div className="group-view-toggle">
              <button
                type="button"
                onClick={() => setViewMode('categories')}
                className={`view-toggle-btn mono text-xs ${viewMode === 'categories' ? 'view-toggle-active' : ''}`}
                title="View categorized groups"
              >
                <LayoutGrid size={13} />
                <span>Grouped Categories</span>
              </button>
              <button
                type="button"
                onClick={() => setViewMode('list')}
                className={`view-toggle-btn mono text-xs ${viewMode === 'list' ? 'view-toggle-active' : ''}`}
                title="View flat indexed list"
              >
                <List size={13} />
                <span>Full List ({filteredList.length})</span>
              </button>
            </div>
          </div>

          {/* View Mode 1: Grouped Categories Grid */}
          {viewMode === 'categories' && (
            <div className="categories-grid" style={{ marginTop: '1rem' }}>
              {Object.keys(categorized).length === 0 ? (
                <div className="mono text-xs text-dim" style={{ padding: '1.5rem', textAlign: 'center', gridColumn: '1 / -1' }}>
                  No gadgets matching "{filterQuery}" in {cleanName}.
                </div>
              ) : (
                Object.entries(categorized).map(([catName, list]) => (
                  <div key={catName} className="category-group-card">
                    <div className="category-group-header">
                      <span className="cat-title mono text-accent-cyan">&gt; {catName}</span>
                      <span className="cat-badge mono text-xs text-dim">({list.length})</span>
                    </div>

                    <div className="category-gadgets-scroll overflow-container">
                      {list.map((item, idx) => {
                        const uniqueKey = `${cleanName}-${catName}-${idx}`;
                        return (
                          <div key={idx} className="category-gadget-row mono text-xs">
                            <button
                              onClick={() => handleCopy(item.addr, `addr-${uniqueKey}`)}
                              className="gadget-addr-copy"
                              title="Copy Address"
                            >
                              <span className="addr-text">{item.addr}</span>
                              {copiedKey === `addr-${uniqueKey}` ? (
                                <Check size={11} className="text-accent-green" />
                              ) : (
                                <Copy size={11} className="text-dim" />
                              )}
                            </button>
                            <span className="gadget-colon">:</span>
                            <div className="gadget-instr-wrap">
                              <span className="instr-text text-accent-green">{item.instr}</span>
                              <button
                                onClick={() => handleCopy(item.instr, `instr-${uniqueKey}`)}
                                className="instr-copy-btn"
                                title="Copy Instructions"
                              >
                                {copiedKey === `instr-${uniqueKey}` ? (
                                  <Check size={11} className="text-accent-green" />
                                ) : (
                                  <Copy size={11} className="text-dim" />
                                )}
                              </button>
                            </div>
                          </div>
                        );
                      })}
                    </div>
                  </div>
                ))
              )}
            </div>
          )}

          {/* View Mode 2: Full List of Gadgets for this Binary */}
          {viewMode === 'list' && (
            <div className="group-list-container overflow-container" style={{ maxHeight: '420px', marginTop: '1rem' }}>
              {filteredList.length === 0 ? (
                <div className="mono text-xs text-dim" style={{ padding: '1.5rem', textAlign: 'center' }}>
                  No gadgets matching "{filterQuery}" in {cleanName}.
                </div>
              ) : (
                <div className="group-list-rows">
                  {filteredList.map((g, idx) => {
                    const addr = g.address || g.addr || '0x0';
                    const instr = g.instructions || g.gadget || '';
                    const uniqueKey = `${cleanName}-list-${idx}`;
                    return (
                      <div key={idx} className="group-list-row mono text-xs">
                        <span className="row-index text-dim">#{(idx + 1).toString().padStart(2, '0')}</span>
                        <button
                          onClick={() => handleCopy(addr, `addr-${uniqueKey}`)}
                          className="gadget-addr-copy"
                          title="Copy Address"
                        >
                          <span className="addr-text">{addr}</span>
                          {copiedKey === `addr-${uniqueKey}` ? (
                            <Check size={11} className="text-accent-green" />
                          ) : (
                            <Copy size={11} className="text-dim" />
                          )}
                        </button>
                        <span className="gadget-colon">:</span>
                        <div className="gadget-instr-wrap">
                          <span className="instr-text text-accent-green">{instr}</span>
                          <button
                            onClick={() => handleCopy(instr, `instr-${uniqueKey}`)}
                            className="instr-copy-btn"
                            title="Copy Instructions"
                          >
                            {copiedKey === `instr-${uniqueKey}` ? (
                              <Check size={11} className="text-accent-green" />
                            ) : (
                              <Copy size={11} className="text-dim" />
                            )}
                          </button>
                        </div>
                      </div>
                    );
                  })}
                </div>
              )}
            </div>
          )}
        </div>
      )}
    </div>
  );
}
